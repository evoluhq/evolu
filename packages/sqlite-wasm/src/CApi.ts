/**
 * SQLite's C API as standalone functions: one for every public C function the
 * binary exports, and one for each of the variadic {@link sqlite3_config},
 * {@link sqlite3_db_config} and {@link sqlite3_vtab_config}, which the binary
 * exports only as the build's `sqlite3__wasm_*` shims.
 *
 * Each function takes {@link SqliteWasmDep} and returns the wasm export itself,
 * typed with branded pointers and raw result codes, so a call costs no
 * JavaScript wrapper. A variadic function whose options need different shims
 * returns a function that passes each option to its shim, as SQLite's
 * JavaScript does. Bind once per database, never per row. Strings are C string
 * pointers; nothing allocates implicitly. A callback parameter takes a function
 * pointer, such as one {@link installWasmFunctions} returns.
 *
 * Each function's documentation gives its wasm type and its signature in the
 * syntax of SQLite's table, where `funcptr:` and the callback's signature stand
 * for a callback argument.
 *
 * Generated by `scripts/generate.mts` from SQLite's own signature table in
 * `scripts/upstream/sqlite3-api-glue.c-pp.js` and the metadata in
 * `scripts/bindings.mts`, with every wasm type checked against the binary's
 * pinned exports. Do not edit.
 *
 * @module
 */

