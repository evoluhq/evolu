/** An option of {@link sqlite3_db_config} and the arguments it takes. */
export type SqliteDbConfigArgs =
  | readonly [op: typeof SQLITE_DBCONFIG_MAINDBNAME, zName: CStringPtr]
  | readonly [
      op: typeof SQLITE_DBCONFIG_LOOKASIDE,
      buf: WasmPtr | NullPtr,
      sz: number,
      cnt: number,
    ]
  | readonly [
      op: SqliteDbConfigIntOp,
      value: number,
      pResult?: WasmPtr | NullPtr,
    ];

/**
 * Changes or reads an option of a connection, returning SQLITE_OK or an error
 * code.
 *
 * - SQLITE_DBCONFIG_MAINDBNAME renames the main schema to zName, which SQLite
 *   does not copy, so it must stay unchanged until the connection closes.
 * - SQLITE_DBCONFIG_LOOKASIDE sets the connection's lookaside allocator to cnt
 *   slots of sz bytes in buf, which must be 8-byte aligned and hold sz times
 *   cnt bytes, or in memory SQLite allocates for a NULL buf. It fails with
 *   SQLITE_BUSY while lookaside memory is in use.
 * - SQLITE_DBCONFIG_FP_DIGITS sets the significant digits of floating-point to
 *   text conversion to value when it is from 4 to 23, leaving the setting
 *   unchanged otherwise, and writes the resulting setting to the int at pResult
 *   unless it is NULL.
 * - Every other option is a flag: a positive value sets it, 0 clears it and a
 *   negative value only reads it, and the resulting 0 or 1 is written to the
 *   int at pResult unless it is NULL. Changing a flag expires the connection's
 *   prepared statements.
 *
 * The C function is variadic, so the binary does not export it. This calls the
 * build's shim for the option's arguments and, as SQLite's JavaScript does,
 * returns SQLITE_MISUSE for any other option without calling wasm.
 *
 * Calls the build's shims, whose signatures come from Evolu's metadata because
 * SQLite's table omits them:
 *
 * - `sqlite3__wasm_db_config_s`, wasm type `i(iii)`, signature
 *   `["sqlite3__wasm_db_config_s", "int", "sqlite3*", "int", "string"]`.
 * - `sqlite3__wasm_db_config_pii`, wasm type `i(iiiii)`, signature
 *   `["sqlite3__wasm_db_config_pii", "int", "sqlite3*", "int", "*", "int",
 *   "int"]`.
 * - `sqlite3__wasm_db_config_ip`, wasm type `i(iiii)`, signature
 *   `["sqlite3__wasm_db_config_ip", "int", "sqlite3*", "int", "int", "int*"]`.
 *
 * See https://sqlite.org/c3ref/db_config.html.
 */
export const sqlite3_db_config = (
  deps: SqliteWasmDep,
): ((db: SqliteDbPtr, ...args: SqliteDbConfigArgs) => SqliteResultCode) => {
  const {
    sqlite3__wasm_db_config_s,
    sqlite3__wasm_db_config_pii,
    sqlite3__wasm_db_config_ip,
  } = deps.sqliteWasm.exports;
  return (db, ...args) => {
    switch (args[0]) {
      case SQLITE_DBCONFIG_MAINDBNAME:
        return sqlite3__wasm_db_config_s(db, args[0], args[1]);
      case SQLITE_DBCONFIG_LOOKASIDE:
        return sqlite3__wasm_db_config_pii(
          db,
          args[0],
          args[1],
          args[2],
          args[3],
        );
      case SQLITE_DBCONFIG_ENABLE_FKEY:
      case SQLITE_DBCONFIG_ENABLE_TRIGGER:
      case SQLITE_DBCONFIG_ENABLE_LOAD_EXTENSION:
      case SQLITE_DBCONFIG_NO_CKPT_ON_CLOSE:
      case SQLITE_DBCONFIG_ENABLE_QPSG:
      case SQLITE_DBCONFIG_TRIGGER_EQP:
      case SQLITE_DBCONFIG_RESET_DATABASE:
      case SQLITE_DBCONFIG_DEFENSIVE:
      case SQLITE_DBCONFIG_WRITABLE_SCHEMA:
      case SQLITE_DBCONFIG_LEGACY_ALTER_TABLE:
      case SQLITE_DBCONFIG_DQS_DML:
      case SQLITE_DBCONFIG_DQS_DDL:
      case SQLITE_DBCONFIG_ENABLE_VIEW:
      case SQLITE_DBCONFIG_LEGACY_FILE_FORMAT:
      case SQLITE_DBCONFIG_TRUSTED_SCHEMA:
      case SQLITE_DBCONFIG_STMT_SCANSTATUS:
      case SQLITE_DBCONFIG_REVERSE_SCANORDER:
      case SQLITE_DBCONFIG_ENABLE_ATTACH_CREATE:
      case SQLITE_DBCONFIG_ENABLE_ATTACH_WRITE:
      case SQLITE_DBCONFIG_ENABLE_COMMENTS:
      case SQLITE_DBCONFIG_FP_DIGITS:
        return sqlite3__wasm_db_config_ip(db, args[0], args[1], args[2] ?? 0);
      default:
        // TypeScript rejects other options, but JavaScript and casts can pass
        // them.
        return SQLITE_MISUSE;
    }
  };
};

